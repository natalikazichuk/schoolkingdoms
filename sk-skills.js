/* очки вмінь за рівні арени: по 1 на рівнях 1–4, далі по 1 кожні два (5, 7, 9…) */
function pointsForLevel(lv) {
  lv = Math.max(0, Math.floor(lv || 0));
  var n = Math.min(lv, 4);
  if (lv >= 5) n += Math.floor((lv - 5) / 2) + 1;
  return n;
}

